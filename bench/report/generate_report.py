#!/usr/bin/env python3
"""Generate the report from actual T1 benchmark summaries only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "results" / "raw"
OUT = ROOT / "report" / "BENCHMARK_REPORT.md"


def latest_t1():
    paths = sorted(RAW.glob("t1_provisioning_*_summary.json"))
    for path in reversed(paths):
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if record.get("test") == "T1_provisioning_latency":
            return path, record
    return None, None


def measured(stats):
    if not isinstance(stats, dict) or not stats.get("n"):
        return "NOT EXECUTED", "NOT EXECUTED", "—"
    vals = " / ".join(str(stats.get(key)) for key in ("min", "mean", "p95", "max"))
    status = "PASS" if stats["p95"] < 60000 else "FAIL"
    return vals, status, str(stats["n"])


def generate():
    t1_path, t1 = latest_t1()
    t1_done = bool(t1 and t1.get("status") == "EXECUTED")
    metrics = (t1 or {}).get("metrics_ms", {})
    api_values, api_status, api_n = measured(metrics.get("api_elapsed"))
    client_values, client_status, client_n = measured(metrics.get("client_post_to_first_http_200"))
    success = (t1 or {}).get("success_rate")
    if t1_done and success is not None:
        success_text = f"{success * 100:.2f}% ({t1.get('successful_runs')} / {t1.get('n')})"
        success_status = "PASS" if success == 1 else "FAIL"
        success_n = str(t1.get("n"))
    else:
        success_text, success_status, success_n = "NOT EXECUTED", "NOT EXECUTED", "—"

    lines = [
        "# FelCloud Benchmark Report", "",
        "## 1. Objective and scope", "",
        "Measure CSTAM 3.0 provisioning behavior using live control plane, gateway, DNS, and OpenStack observations. This report includes only actual T1 run records; no mock, estimated, or placeholder measurements are used.", "",
        "## 2. Test environment", "",
        "See [ENVIRONMENT.md](../ENVIRONMENT.md). The snapshot is generated by running `bench/preflight.py`; this report does not reuse discovery or sandbox network errors as environment measurements.", "",
        "## 3. Methodology", "",
        "T1 records API response stage durations as supplied by the control plane and client-side durations using `time.perf_counter`. UTC event timestamps are recorded for request and probe events. The client-side end-to-end metric starts when the HTTP client begins the POST and ends at the first HTTP 200 through the configured VIP with the sandbox hostname in the Host header. The control plane currently supplies stage durations, not exact per-stage event timestamps.", "",
        "T1 smoke provisions one real uniquely named `bench-` sandbox and cleans it in `finally`. Full T1 is sequential. Image-cache cold/warm classification is NOT EXECUTED because the harness cannot control or verify cache state.", "",
        "T2–T7 are deferred and their scenario implementations are not included in this revision.", "",
        "## 4. Results summary", "",
        "Times are milliseconds. NOT EXECUTED means no valid live samples are present.", "",
        "| Metric | Target | Measured (min / mean / p95 / max) | Pass/Fail | n |",
        "|---|---|---|---|---|",
        f"| T1 control-plane API duration | Informational | {api_values} | {api_status} | {api_n} |",
        f"| T1 client POST to first VIP HTTP 200 | p95 < 60,000 ms | {client_values} | {client_status} | {client_n} |",
        f"| T1 successful routes | Informational | {success_text} | {success_status} | {success_n} |",
    ]
    for test, name, target in [
        ("T2", "Concurrent provisioning stress", "100% success at 10+ concurrency; 0 IP conflicts and misroutes"),
        ("T3", "Gateway failover", "< 3 s"),
        ("T4", "IP recycling", "< 5 s"),
        ("T5", "Lease expiry and teardown", "Complete teardown verification"),
        ("T6", "Reload and rollback", "0 request drops; rollback < 1 s"),
        ("T7", "Network isolation", "0 successful forbidden connections"),
    ]:
        lines.append(f"| {test} — {name} | {target} | NOT EXECUTED | NOT EXECUTED | — |")

    lines += ["", "## 5. Detailed results", ""]
    if t1_done:
        lines += ["### T1 — Provisioning latency", "", f"Status: **{t1['status']}**.", "",
                  f"Raw samples: `../results/raw/{Path(t1['raw_csv']).name}`.", "",
                  f"Summary: `../results/raw/{t1_path.name}`.", ""]
        if t1.get("chart_generated") and t1.get("chart_png"):
            lines += [f"![T1 stage duration chart](../results/charts/{Path(t1['chart_png']).name})", ""]
        lines += [f"Successful runs: {t1.get('successful_runs')}; unsuccessful runs: {t1.get('failed_runs')}.", ""]
    else:
        reason = "; ".join((t1 or {}).get("reason", [])) or "No live T1 run record exists."
        lines += ["### T1 — Provisioning latency", "", "Status: **NOT EXECUTED**.", "", f"Reason: {reason}", ""]
    for test, name, reason in [
        ("T2", "Concurrent provisioning stress", "Scenario implementation deferred until successful real T1 smoke review."),
        ("T3", "Gateway failover", "Scenario implementation deferred until successful real T1 smoke review."),
        ("T4", "IP recycling", "Scenario implementation deferred until successful real T1 smoke review."),
        ("T5", "Lease expiry and teardown", "Scenario implementation deferred until successful real T1 smoke review."),
        ("T6", "Reload and rollback", "Scenario implementation deferred until successful real T1 smoke review."),
        ("T7", "Network isolation", "Scenario implementation deferred until successful real T1 smoke review."),
    ]:
        lines += [f"### {test} — {name}", "", "Status: **NOT EXECUTED**.", "", reason, ""]
    lines += [
        "## 6. Bugs and anomalies", "",
        "See [bugs_found.md](../bugs_found.md). Report only defects reproduced by a live benchmark run.", "",
        "## 7. Limitations and threats to validity", "",
        "This report is limited to T1 evidence present on disk. A smoke run contains one sample and cannot establish distribution tails. Cold/warm image cache conditions are not measured. T2–T7 have not been implemented in this revision.", "",
        "## 8. Reproduction", "",
        "After reviewing successful preflight output, run `bench/.venv/bin/python bench/tests/t1_provisioning_latency.py --smoke` for one live sample or `bench/.venv/bin/python bench/tests/t1_provisioning_latency.py` for configured sequential runs. Results are written to `bench/results/raw/` and a chart, when source samples exist, to `bench/results/charts/`.", "",
        "## 9. Challenge scoring mapping", "",
        "- Stress test (15 points): T2 NOT EXECUTED; implementation deferred.",
        "- Teardown (10 points): T5 NOT EXECUTED; implementation deferred.",
        "- Isolation (5 points): T7 NOT EXECUTED; implementation deferred.", "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT)


if __name__ == "__main__":
    generate()
